function [iPar,iiLogL] = mcmcParallelBlock(countryText,mcSteps,...
    weeklyILI,weeklyLab,monthlyCaseRSV,indicesMonthlyRSV,...
    seroprevData,indicesSeroPreg,indicesSeroAge,...
    seroprevDataMeta,indicesSeroAgeMeta,...
    seroprevDataHKRec,indicesSeroAgeHK,...
    dataPitzerIncubation, dataPitzerInfectious,...
    stateM,...
    stateS0, stateS1, stateS2, stateS3,...
    stateE0, stateE1, stateE2, stateE3,...
    stateI0, stateI1, stateI2, stateI3,...
    stateA0, stateA1, stateA2, stateA3,...
    stateR0, stateR1, stateR2, stateR3,...
    stateZ,...
    probVmAb, probVvax,...
    totalPopulation, ageGroupDefRangeAll, muBirthRate,populationSizeTable,populationSizeTableRev,...
    phyContactMatr, conversationContactMatr,...
    dateZero,dateStart,cutoffCOVID, numDays, numTimeSteps, dt,...
    parameters,parameterSteps,parameterStepFloor,lowerLimit,upperLimit,blockUpdateGroup,proposalCov1415)

    goodMC = false;
    numWhileLoop = 0;
    numPars = length(parameters);
    checkpointEvery = max(1,floor(mcSteps/100));
    adaptUntil = max(checkpointEvery,floor(0.2*mcSteps));

    parameterSteps = max(parameterSteps,parameterStepFloor);
    parameterSteps = min([parameterSteps;upperLimit-lowerLimit]);

    while goodMC == false
        numWhileLoop = numWhileLoop+1;
        iPar = nan(mcSteps,numPars);
        iiLogL = nan(mcSteps,1);
        iiLogLArr = nan(mcSteps,7);
        peakTransmissionScale = nan(mcSteps,1);
        nAcceptTotal = zeros(1,numPars);
        nAcceptWindow = zeros(1,numPars);
        lastCheckpoint = 0;

        parameters_c = parameters;
        logPrior = logPriorDistribution(parameters_c);
        [sumLogL,logLArr] = calcMCMCTotalLogLikelihood(parameters_c,...
            weeklyILI,weeklyLab,monthlyCaseRSV,indicesMonthlyRSV,...
            seroprevData,indicesSeroPreg,indicesSeroAge,...
            seroprevDataMeta,indicesSeroAgeMeta,...
            seroprevDataHKRec,indicesSeroAgeHK,...
            dataPitzerIncubation, dataPitzerInfectious,...
            stateM,...
            stateS0, stateS1, stateS2, stateS3,...
            stateE0, stateE1, stateE2, stateE3,...
            stateI0, stateI1, stateI2, stateI3,...
            stateA0, stateA1, stateA2, stateA3,...
            stateR0, stateR1, stateR2, stateR3,...
            stateZ,...
            probVmAb, probVvax,...
            totalPopulation, ageGroupDefRangeAll, muBirthRate,populationSizeTable,populationSizeTableRev,...
            phyContactMatr, conversationContactMatr,...
            dateZero,dateStart,cutoffCOVID, numDays, numTimeSteps, dt);

        logLikelihood = logPrior+sumLogL;

        for tt = 1:mcSteps
                [tempNew,logProposalCorrection] = mcmcProposal(parameters_c,parameterSteps,lowerLimit,upperLimit,proposalCov1415);
            for ii = 1:length(blockUpdateGroup(:,1))
                parameters_mc = parameters_c;
                    acceptIdx = blockUpdateGroup(ii,1):blockUpdateGroup(ii,2);
                    parameters_mc(acceptIdx) = tempNew(acceptIdx);
                    if any(parameters_mc(acceptIdx) < lowerLimit(acceptIdx)) || ...
                            any(parameters_mc(acceptIdx) > upperLimit(acceptIdx)) || ...
                            any(parameterConstraint(parameters_mc)>0)
                        continue;
                    end
                logPrior_new = logPriorDistribution(parameters_mc);
                [sumLogL_new,logLArr_new] = calcMCMCTotalLogLikelihood(parameters_mc,...
                    weeklyILI,weeklyLab,monthlyCaseRSV,indicesMonthlyRSV,...
                    seroprevData,indicesSeroPreg,indicesSeroAge,...
                    seroprevDataMeta,indicesSeroAgeMeta,...
                    seroprevDataHKRec,indicesSeroAgeHK,...
                    dataPitzerIncubation, dataPitzerInfectious,...
                    stateM,...
                    stateS0, stateS1, stateS2, stateS3,...
                    stateE0, stateE1, stateE2, stateE3,...
                    stateI0, stateI1, stateI2, stateI3,...
                    stateA0, stateA1, stateA2, stateA3,...
                    stateR0, stateR1, stateR2, stateR3,...
                    stateZ,...
                    probVmAb, probVvax,...
                    totalPopulation, ageGroupDefRangeAll, muBirthRate,populationSizeTable,populationSizeTableRev,...
                    phyContactMatr, conversationContactMatr,...
                    dateZero,dateStart,cutoffCOVID, numDays, numTimeSteps, dt);

                logLikelihood_new = logPrior_new + sumLogL_new;
                logAlpha = min(0,logLikelihood_new-logLikelihood + ...
                    sum(logProposalCorrection(acceptIdx)));
                alpha = exp(logAlpha);
                uu = rand;
                if uu <= alpha
                    parameters_c = parameters_mc;
                    logLikelihood = logLikelihood_new;
                    logLArr = logLArr_new;
                    nAcceptTotal(acceptIdx) = nAcceptTotal(acceptIdx)+1;
                    nAcceptWindow(acceptIdx) = nAcceptWindow(acceptIdx)+1;
                end
            end
            iiLogL(tt,:) = logLikelihood;
            iiLogLArr(tt,:) = logLArr;
            iPar(tt,:) = parameters_c;
            if numPars >= 15
                peakTransmissionScale(tt,1) = parameters_c(14) * (1 + parameters_c(15));
            end

            if mod(tt,checkpointEvery) == 0 || tt == mcSteps
                pAccept = nAcceptTotal/tt;

                if tt <= adaptUntil
                    windowCount = tt-lastCheckpoint;
                    pAcceptWindow = nAcceptWindow/max(windowCount,1);
                    parameterSteps(pAcceptWindow > 0.7) = parameterSteps(pAcceptWindow > 0.7)*1.2;
                    parameterSteps(pAcceptWindow < 0.3) = parameterSteps(pAcceptWindow < 0.3)/1.25;
                    parameterSteps = max(parameterSteps,parameterStepFloor);
                    parameterSteps = min([parameterSteps;upperLimit-lowerLimit]);
                    nAcceptWindow(:) = 0;
                    lastCheckpoint = tt;
                end

                write_matrix_new(parameterSteps,strcat('mcmc_result/',countryText,'_parameter_step.csv'),'w',',','dec');
                write_matrix_new(iPar(1:tt,:),strcat('mcmc_result/',countryText,'_mcmc_res.csv'),'w',',','dec');
                write_matrix_new(iiLogL(1:tt,:),strcat('mcmc_result/',countryText,'_log_likelihood.csv'),'w',',','dec');
                write_matrix_new(iiLogLArr(1:tt,:),strcat('mcmc_result/',countryText,'_log_likelihood_component.csv'),'w',',','dec');
                write_matrix_new(peakTransmissionScale(1:tt,:),strcat('mcmc_result/',countryText,'_peak_transmission_scale.csv'),'w',',','dec');
                disp('MCMC');
                display(tt/mcSteps);
                disp('Acceptance probability');
                display(pAccept);

                if any(pAccept > 0.7) || any(pAccept < 0.3)
                    goodMC = false;
                    if numWhileLoop < 10
                        if tt/mcSteps >= 0.02
                            continue;
                        end
                    else
                        goodMC = true;
                    end
                else
                    goodMC = true;
                end
            end
        end
    end
end



